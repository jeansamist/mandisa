"use client";

import { useState, useTransition } from "react";
import type { AdminVariant } from "@/lib/ms-types";
import { stockStatusLabels } from "@/components/ms/format";
import { Badge } from "@/components/ms/ui";
import { createVariant, updateVariant } from "../actions";
import { Feedback } from "../_shared/feedback";

const colorLabels: Record<string, string> = {
  naturalBlack: "Noir naturel",
  deepBrown: "Brun profond",
  warmBrown: "Brun chaud",
};

const statusTone = {
  inStock: "good",
  lowStock: "warn",
  preorder: "neutral",
  soldOut: "bad",
} as const;

type Feedback = { ok: boolean; message: string } | null;

/** One editable variant row: price, stock (with reason), threshold, pre-order. */
export function VariantRow({ variant }: { variant: AdminVariant }) {
  const [price, setPrice] = useState(String(variant.priceXaf));
  const [stock, setStock] = useState(String(variant.stockOnHand));
  const [reason, setReason] = useState<"entry" | "correction">("entry");
  const [note, setNote] = useState("");
  const [threshold, setThreshold] = useState(String(variant.lowStockThreshold));
  const [preorder, setPreorder] = useState(variant.preorderEnabled);
  const [feedback, setFeedback] = useState<Feedback>(null);
  const [pending, startTransition] = useTransition();
  const stockChanged = Number(stock) !== variant.stockOnHand;

  const save = () => {
    setFeedback(null);
    startTransition(async () => {
      const result = await updateVariant(variant.sku, {
        priceXaf: Number(price),
        stockOnHand: Number(stock),
        stockReason: reason,
        stockNote: note.trim() || null,
        lowStockThreshold: Number(threshold),
        preorderEnabled: preorder,
      });
      setFeedback(
        result.ok
          ? { ok: true, message: "Enregistré." }
          : { ok: false, message: result.message },
      );
      if (result.ok) setNote("");
    });
  };

  const label = `${variant.lengthInches}" · ${colorLabels[variant.color] ?? variant.color} · ${variant.capSize}`;
  return (
    <tr>
      <td>
        <p className="font-medium">{label}</p>
        <p className="font-mono text-xs text-ms-ink/50">{variant.sku}</p>
      </td>
      <td>
        <input
          aria-label={`Prix (FCFA) ${label}`}
          className="ms-input w-28"
          type="number"
          min={1}
          step={500}
          value={price}
          onChange={(e) => setPrice(e.target.value)}
        />
      </td>
      <td>
        <div className="grid gap-1">
          <input
            aria-label={`Stock physique ${label}`}
            className="ms-input w-20"
            type="number"
            min={0}
            value={stock}
            onChange={(e) => setStock(e.target.value)}
          />
          {stockChanged && (
            <>
              <select
                aria-label={`Motif du changement de stock ${label}`}
                className="ms-input w-32 text-xs"
                value={reason}
                onChange={(e) =>
                  setReason(e.target.value as "entry" | "correction")
                }
              >
                <option value="entry">Entrée (réception)</option>
                <option value="correction">Correction</option>
              </select>
              <input
                aria-label={`Note ${label}`}
                className="ms-input w-32 text-xs"
                placeholder="Note (facultatif)"
                maxLength={200}
                value={note}
                onChange={(e) => setNote(e.target.value)}
              />
            </>
          )}
        </div>
      </td>
      <td className="text-sm">
        {variant.available} / {variant.stockReserved}
      </td>
      <td>
        <input
          aria-label={`Seuil de stock faible ${label}`}
          className="ms-input w-16"
          type="number"
          min={0}
          max={100}
          value={threshold}
          onChange={(e) => setThreshold(e.target.value)}
        />
      </td>
      <td>
        <input
          aria-label={`Précommande ${label}`}
          type="checkbox"
          checked={preorder}
          onChange={(e) => setPreorder(e.target.checked)}
        />
      </td>
      <td>
        <Badge tone={statusTone[variant.status]}>
          {stockStatusLabels[variant.status]}
        </Badge>
      </td>
      <td>
        <div className="grid gap-1">
          <button
            type="button"
            className="ms-btn px-3 py-1.5 text-xs"
            onClick={save}
            disabled={pending}
          >
            {pending ? "…" : "Enregistrer"}
          </button>
          <Feedback state={feedback} />
        </div>
      </td>
    </tr>
  );
}

/** Adds a length × color × cap size combination; the SKU is generated by the API. */
export function AddVariantForm({ code }: { code: string }) {
  const [values, setValues] = useState({
    lengthInches: "14",
    color: "naturalBlack",
    capSize: "M" as "S" | "M" | "L",
    priceXaf: "",
    stockOnHand: "0",
    lowStockThreshold: "2",
    preorderEnabled: false,
  });
  const [feedback, setFeedback] = useState<Feedback>(null);
  const [pending, startTransition] = useTransition();

  const submit = (event: React.FormEvent) => {
    event.preventDefault();
    setFeedback(null);
    startTransition(async () => {
      const result = await createVariant(code, {
        lengthInches: Number(values.lengthInches),
        color: values.color.trim(),
        capSize: values.capSize,
        priceXaf: Number(values.priceXaf),
        stockOnHand: Number(values.stockOnHand),
        lowStockThreshold: Number(values.lowStockThreshold),
        preorderEnabled: values.preorderEnabled,
      });
      setFeedback(
        result.ok
          ? { ok: true, message: "Variante ajoutée." }
          : { ok: false, message: result.message },
      );
    });
  };

  return (
    <form
      onSubmit={submit}
      className="grid gap-3 border-t border-ms-ink/10 pt-4"
    >
      <h3 className="text-sm font-semibold">Ajouter une variante</h3>
      <div className="grid gap-3 sm:grid-cols-3 lg:grid-cols-7">
        <label className="ms-label">
          Longueur (pouces)
          <input
            className="ms-input"
            type="number"
            min={6}
            max={40}
            value={values.lengthInches}
            onChange={(e) =>
              setValues({ ...values, lengthInches: e.target.value })
            }
            required
          />
        </label>
        <label className="ms-label">
          Couleur
          <input
            className="ms-input"
            list="variant-colors"
            value={values.color}
            onChange={(e) => setValues({ ...values, color: e.target.value })}
            pattern="[a-zA-Z]{2,30}"
            required
          />
          <datalist id="variant-colors">
            {Object.entries(colorLabels).map(([value, label]) => (
              <option key={value} value={value}>
                {label}
              </option>
            ))}
          </datalist>
        </label>
        <label className="ms-label">
          Bonnet
          <select
            className="ms-input"
            value={values.capSize}
            onChange={(e) =>
              setValues({
                ...values,
                capSize: e.target.value as "S" | "M" | "L",
              })
            }
          >
            <option>S</option>
            <option>M</option>
            <option>L</option>
          </select>
        </label>
        <label className="ms-label">
          Prix (FCFA)
          <input
            className="ms-input"
            type="number"
            min={1}
            step={500}
            value={values.priceXaf}
            onChange={(e) => setValues({ ...values, priceXaf: e.target.value })}
            required
          />
        </label>
        <label className="ms-label">
          Stock initial
          <input
            className="ms-input"
            type="number"
            min={0}
            value={values.stockOnHand}
            onChange={(e) =>
              setValues({ ...values, stockOnHand: e.target.value })
            }
            required
          />
        </label>
        <label className="ms-label">
          Seuil stock faible
          <input
            className="ms-input"
            type="number"
            min={0}
            max={100}
            value={values.lowStockThreshold}
            onChange={(e) =>
              setValues({ ...values, lowStockThreshold: e.target.value })
            }
            required
          />
        </label>
        <label className="flex items-center gap-2 self-end pb-2 text-sm">
          <input
            type="checkbox"
            checked={values.preorderEnabled}
            onChange={(e) =>
              setValues({ ...values, preorderEnabled: e.target.checked })
            }
          />
          Précommande
        </label>
      </div>
      <div className="flex flex-wrap items-center gap-3">
        <button className="ms-btn" disabled={pending}>
          {pending ? "Ajout…" : "Ajouter la variante"}
        </button>
        <Feedback state={feedback} />
      </div>
    </form>
  );
}
